#!/usr/bin/env python3
"""Generate benchmark vaults for the shale-vs-rivals harness.

Creates deterministic Markdown corpora under bench/vaults/:

  gen_vault.py dnd      copy of the real Dnd vault (skips its app metadata)
  gen_vault.py medium   ~2000 synthetic notes
  gen_vault.py large    ~20000 synthetic notes

Synthetic notes carry the features every contender indexes: YAML frontmatter
with tags, dense [[wikilinks]], tasks, tables, code fences, and image embeds.
Deterministic (seeded) so runs are reproducible and diffs are meaningful.
"""

import argparse
import random
import shutil
import sys
from pathlib import Path

BENCH = Path(__file__).resolve().parent
VAULTS = BENCH / "vaults"
REAL_DND = Path.home() / "Nextcloud" / "Documents" / "Dnd"
# App metadata we never copy: each app regenerates its own inside the copy.
SKIP_DIRS = {".obsidian", ".shale", ".zennotes", ".trash", "trash"}

TOPICS = [
    "campaign", "session", "npc", "location", "item", "quest", "monster",
    "deity", "faction", "spell", "loot", "puzzle", "trap", "timeline",
]
WORDS = (
    "the party travels through the misty ruins of an ancient keep seeking "
    "forgotten relics and dangerous secrets hidden beneath the stone floor"
).split()


def lorem(rng: random.Random, n: int) -> str:
    return " ".join(rng.choice(WORDS) for _ in range(n)).capitalize()


def make_note(rng: random.Random, title: str, all_titles: list[str], folder: str) -> str:
    """Build one synthetic note exercising every indexed feature."""
    links = rng.sample(all_titles, k=min(6, len(all_titles)))
    tags = rng.sample(TOPICS, k=3)
    lines = [
        "---",
        f"title: {title}",
        f"tags: [{', '.join(tags)}]",
        f"created: 2026-01-{rng.randint(1, 28):02d}",
        "---",
        "",
        f"# {title}",
        "",
        lorem(rng, 60),
        "",
        "## Links",
        "",
    ]
    lines += [f"- see [[{t}]] for the details" for t in links]
    lines += [
        "",
        "## Tasks",
        "",
        "- [x] prep the map",
        "- [ ] brief the players",
        "- [/] partially done thing",
        "",
        "## Table",
        "",
        "| enemy | hp | ac |",
        "|---|---|---|",
        f"| goblin | {rng.randint(5, 12)} | 12 |",
        f"| orc | {rng.randint(10, 20)} | 13 |",
        "",
        "## Code",
        "",
        "```rust",
        "fn roll() -> u32 { 1 + 6 }",
        "```",
        "",
        f"![[diagram-{rng.randint(1, 50)}.png]]",
        "",
    ]
    return "\n".join(lines)


def gen_synthetic(name: str, count: int) -> Path:
    """Write `count` synthetic notes spread over topic folders."""
    rng = random.Random(1234)  # deterministic corpus
    out = VAULTS / name
    if out.exists():
        shutil.rmtree(out)
    # Titles first so links can reference notes that exist anywhere in the vault.
    titles = [f"{topic.capitalize()} {i:05d}" for i, topic in enumerate(
        (TOPICS * (count // len(TOPICS) + 1))[:count])]
    for i, (title, topic) in enumerate(zip(titles, (TOPICS * (count // len(TOPICS) + 1))[:count])):
        folder = out / topic
        folder.mkdir(parents=True, exist_ok=True)
        body = make_note(rng, title, titles, folder.name)
        (folder / f"{title}.md").write_text(body, encoding="utf-8")
    (out / "Welcome.md").write_text(
        "# Welcome\n\nThis vault is generated by bench/gen_vault.py.\n\n"
        "[[Campaign 00000]]\n", encoding="utf-8")
    return out


def gen_dnd() -> Path:
    """Copy the real Dnd vault, minus every app's metadata dirs."""
    out = VAULTS / "dnd"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(REAL_DND, out,
                    ignore=shutil.ignore_patterns(*SKIP_DIRS))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("corpus", choices=["dnd", "medium", "large"])
    args = ap.parse_args()
    counts = {"medium": 2000, "large": 20000}
    out = gen_dnd() if args.corpus == "dnd" else gen_synthetic(
        args.corpus, counts[args.corpus])
    n = sum(1 for _ in out.rglob("*.md"))
    print(f"{out} ({n} notes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
